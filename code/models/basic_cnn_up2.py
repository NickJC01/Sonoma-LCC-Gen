train_batches = []
# val_batches = []
test_batches = []

for batch in dataset.to_batches():
    # Add a random value 0–1 for each row
    rand = pc.random(batch.num_rows)
    batch = batch.append_column("split_rand", rand)

    # Boolean masks
    train_mask = pc.less(batch['split_rand'], 0.85)                # 70%
    # val_mask   = pc.and_(
    #     pc.greater_equal(batch['split_rand'], 0.7),
    #     pc.less(batch['split_rand'], 0.85)                        # 15%
    # )
    test_mask  = pc.greater_equal(batch['split_rand'], 0.85)      # 15%

    train_batches.append(batch.filter(train_mask))
    # val_batches.append(batch.filter(val_mask))
    test_batches.append(batch.filter(test_mask))

# Combine batches
train_table = pa.Table.from_batches(train_batches)
# val_table   = pa.Table.from_batches(val_batches)
test_table  = pa.Table.from_batches(test_batches)

df_train = train_table.to_pandas()
# df_val   = val_table.to_pandas()
df_test  = test_table.to_pandas()

# --- Train set
X_train = df_train[feature_cols].to_numpy(dtype=np.float32)
y_train = df_train['label'].to_numpy(dtype=np.int32)

# --- Validation set
