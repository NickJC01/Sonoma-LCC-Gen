import tensorflow as tf
from tensorflow.keras import layers, models

tf.keras.backend.clear_session()

model = models.Sequential([
    layers.Input(shape=(n_features,)),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.2),
    layers.Dense(64, activation='relu'),
    layers.Dropout(0.2),
    layers.Dense(num_classes, activation='softmax')  # 0–19 labels
])

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',  # because y is int labels
    metrics=['accuracy']
)

model.summary()

history = model.fit(
    X_train, y_train,
    epochs=8,          # start small; tune later
    batch_size=256,
    validation_split=0.1275,
    verbose=1
)

test_loss, test_acc = model.evaluate(X_test, y_test, verbose=0)
