from pyproj import CRS as PJ_CRS, Transformer

# crs might be a rasterio CRS object, a string, or None
def to_wgs84_transformer(crs_obj_or_str):
    src = PJ_CRS.from_user_input(crs_obj_or_str or CRS_STR)
    dst = PJ_CRS.from_epsg(4326)
    return Transformer.from_crs(src, dst, always_xy=True)

def ensure_alignment(emb_ds, lab_ds):
    """Return (E64, Lab, transform, crs) with embeddings aligned to label grid."""
    Lab = lab_ds.read(1)
    H, W = Lab.shape
    dst_transform, dst_crs = lab_ds.transform, lab_ds.crs

    same_grid = (
        emb_ds.crs == dst_crs and
        emb_ds.transform == dst_transform and
        emb_ds.width == W and emb_ds.height == H
    )

    bands = min(64, emb_ds.count)
    if same_grid:
        E = emb_ds.read(indexes=list(range(1, bands+1))).astype(np.float32)
        return E, Lab, dst_transform, dst_crs

    # Reproject embeddings → label grid
    E = np.empty((bands, H, W), dtype=np.float32)
    for b in range(bands):
        src = emb_ds.read(b+1).astype(np.float32, copy=False)
        dst = np.empty((H, W), dtype=np.float32)
        reproject(
            source=src,
            destination=dst,
            src_transform=emb_ds.transform,
            src_crs=emb_ds.crs,
            dst_transform=dst_transform,
            dst_crs=dst_crs,
            resampling=RS.bilinear,
            num_threads=2
        )
        E[b] = dst
    return E, Lab, dst_transform, dst_crs

def write_parquet_for_pair(idx, emb_path: Path, lab_path: Path, drop_unlabeled=False):
    with rasterio.open(emb_path) as E, rasterio.open(lab_path) as L:
        E64, Lab, transform, crs = ensure_alignment(E, L)  # E64: (bands, H, W)
        bands = E64.shape[0]
        if bands < 1:
            raise RuntimeError(f"No bands in {emb_path.name}")

        H, W = Lab.shape
        A = E64.reshape(bands, -1).T  # (N, bands)
        y_vec = Lab.reshape(-1).astype(np.int32)

        if drop_unlabeled:
            mask = (y_vec != 0)
            A, y_vec = A[mask], y_vec[mask]
            keep = np.where(mask)[0]
        else:
            keep = np.arange(H*W)

        rows = (keep // W).astype(np.int32)
        cols = (keep %  W).astype(np.int32)

        xs, ys = rasterio.transform.xy(transform, rows, cols, offset='center')
        xs = np.asarray(xs, dtype=np.float64)
        ys = np.asarray(ys, dtype=np.float64)

        # coords → WGS84
        to_wgs84 = to_wgs84_transformer(crs)   # where `crs` came from the raster/array
        lons, lats = to_wgs84.transform(xs, ys)

        cell_id = (cols.astype(np.int64) << 32) | rows.astype(np.int64)

        names = ["cell_id","i","j","x","y","lon","lat","label"] + [f"A{k:02d}" for k in range(bands)]
        arrays = [
            pa.array(cell_id),
            pa.array(rows), pa.array(cols),
            pa.array(xs), pa.array(ys),
            pa.array(lons), pa.array(lats),
            pa.array(y_vec)
        ] + [pa.array(A[:,k]) for k in range(bands)]

        tbl = pa.Table.from_arrays(arrays, names=names)
        out_path = OUT_DIR / f"tile_{idx:04d}.parquet"
        pq.write_table(tbl, out_path, compression="zstd", version="2.6", data_page_version="2.0")
        return out_path

