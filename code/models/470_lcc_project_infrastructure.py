def to_wgs84_transformer(crs_obj_or_str):
    """Build a pyproj Transformer from raster CRS → EPSG:4326."""
    src = PJ_CRS.from_user_input(crs_obj_or_str)
    dst = PJ_CRS.from_epsg(4326)
    return Transformer.from_crs(src, dst, always_xy=True)

def write_parquet_from_emb(idx: int, emb_path: Path):
    """Create a parquet tile from embeddings only, with dummy label=0."""
    with rasterio.open(emb_path) as E:
        bands = min(64, E.count)  # normally 64
        if bands < 1:
            raise RuntimeError(f"No bands in {emb_path.name}")

        H, W = E.height, E.width
        E64 = E.read(indexes=list(range(1, bands+1))).astype(np.float32)

        A = E64.reshape(bands, -1).T  # (N, bands), row-major

        N = H * W
        y_vec = np.zeros(N, dtype=np.int32)

        rows = np.arange(N, dtype=np.int32) // W
        cols = np.arange(N, dtype=np.int32) %  W

        xs, ys = raster_xy(E.transform, rows, cols, offset='center')
        xs = np.asarray(xs, dtype=np.float64)
        ys = np.asarray(ys, dtype=np.float64)

        tf = to_wgs84_transformer(E.crs if E.crs is not None else "EPSG:32610")
        lons, lats = tf.transform(xs, ys)

        cell_id = (cols.astype(np.int64) << 32) | rows.astype(np.int64)

        names = ["cell_id","i","j","x","y","lon","lat","label"] + [f"A{k:02d}" for k in range(bands)]
        arrays = [
            pa.array(cell_id),
            pa.array(rows), pa.array(cols),
            pa.array(xs), pa.array(ys),
            pa.array(lons), pa.array(lats),
            pa.array(y_vec)  # placeholder labels
        ] + [pa.array(A[:, k]) for k in range(bands)]

        tbl = pa.Table.from_arrays(arrays, names=names)
        out_path = OUT_DIR / f"tile_{idx:04d}.parquet"
        pq.write_table(tbl, out_path, compression="zstd", version="2.6", data_page_version="2.0")
        return out_path

