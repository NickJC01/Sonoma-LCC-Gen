def lonlat_bounds_from_parquet(path):
    """
    Use Parquet column stats (no full load) to get [minLon, minLat, maxLon, maxLat].
    Falls back to reading lon/lat if stats not present.
    """
    pf = pq.ParquetFile(path)
    min_lon = min_lat = float('inf')
    max_lon = max_lat = float('-inf')
    have_stats = False

    for rg in range(pf.num_row_groups):
        md = pf.metadata.row_group(rg)
        col_ix = {md.column(i).path_in_schema: i for i in range(md.num_columns)}
        for col_name, is_lon in (('lon', True), ('lat', False)):
            if col_name in col_ix:
                cmeta = md.column(col_ix[col_name])
                stats = cmeta.statistics
                if stats and stats.has_min_max:
                    have_stats = True
                    if is_lon:
                        min_lon = min(min_lon, float(stats.min))
                        max_lon = max(max_lon, float(stats.max))
                    else:
                        min_lat = min(min_lat, float(stats.min))
                        max_lat = max(max_lat, float(stats.max))

    if not have_stats:
        table = pq.read_table(path, columns=['lon', 'lat'])
        min_lon = float(table['lon'].min())
        max_lon = float(table['lon'].max())
        min_lat = float(table['lat'].min())
        max_lat = float(table['lat'].max())

    return min_lon, min_lat, max_lon, max_lat

