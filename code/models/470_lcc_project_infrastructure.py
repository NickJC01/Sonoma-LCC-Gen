def _read_label_series(parquet_path: str) -> pd.Series:
    """Return a pandas Series of label codes from the parquet."""
    if _USE_PYARROW:
        tbl = pq.read_table(parquet_path, columns=["label"])
        s = tbl.column("label").to_pandas()
    else:
        s = pd.read_parquet(parquet_path, columns=["label"])
        if isinstance(s, pd.DataFrame):
            s = s["label"]
    return s.astype("int32", copy=False)

def summarize_tile(parquet_path: str, drop_unclassified: bool = False) -> pd.DataFrame:
    """
    Summarize label distribution for a single tile parquet.
    Returns a DataFrame with: code, label, pixels, area_km2, pct.
    """
    labels = _read_label_series(parquet_path)
    total = int(labels.size)

    vc = labels.value_counts().sort_values(ascending=False)
    df = (
        vc.rename("pixels")
          .rename_axis("code")
          .reset_index()
          .assign(
              label=lambda d: d["code"].map(LABEL_MAP).fillna("UNKNOWN"),
              area_km2=lambda d: d["pixels"] * PIXEL_TO_KM2,
              pct=lambda d: (d["pixels"] / total) * 100.0,
          )
          .loc[:, ["code", "label", "pixels", "area_km2", "pct"]]
    )

    if drop_unclassified:
        df = df.loc[df["code"] != 0].reset_index(drop=True)

    # Nice formatting for display
    df["area_km2"] = df["area_km2"].round(4)
    df["pct"] = df["pct"].round(4)

    # Add a footer row with totals (area should equal total*1e-4)
    total_row = pd.DataFrame(
        [{
            "code": -1,
            "label": "TOTAL",
            "pixels": total,
            "area_km2": round(total * PIXEL_TO_KM2, 4),
            "pct": 100.0
        }]
    )
    return pd.concat([df, total_row], ignore_index=True)

def check_ocean_tile(parquet_path: str, water_code: int = 19) -> dict:
    """
    For a tile expected to be ocean: verify that any labeled pixels are WATER.
    Returns a dict with counts and pass/fail flag.
    """
    labels = _read_label_series(parquet_path)
    total = int(labels.size)
    nonzero = labels[labels != 0]
    non_water = nonzero[nonzero != water_code]

    return {
        "tile": os.path.basename(parquet_path),
        "total_pixels": total,
        "labeled_pixels": int(nonzero.size),
        "defined_pixels": int(non_water.size),
        "ok": int(non_water.size) == 0,
    }

