def show_labeled_pixels(tile_parquet_path, bins=512, label_ok=(0, -1)):
    """
    Paint labeled pixels for a single Parquet tile (cells with label not in label_ok).
    - bins: raster resolution used for the overlay (higher = finer, but heavier)
    - label_ok: codes considered 'unlabeled' (0 and -1 by default)
    """
    # Read minimal columns
    tbl = pq.read_table(tile_parquet_path, columns=["lon", "lat", "label"])
    df = tbl.to_pandas()

    # Keep only labeled cells
    unlabeled = set(label_ok)
    msk = ~df["label"].isin(unlabeled)
    if msk.sum() == 0:
        print("No labeled pixels in this tile.")
        # Still show tile extent for context
        xmin, xmax = df["lon"].min(), df["lon"].max()
        ymin, ymax = df["lat"].min(), df["lat"].max()
        m = folium.Map(location=[(ymin+ymax)/2, (xmin+xmax)/2], zoom_start=12, control_scale=True)
        folium.Rectangle(bounds=[(ymin, xmin), (ymax, xmax)], color="gray", weight=2, fill=False).add_to(m)
        display(m)
        return

    lon = df.loc[msk, "lon"].to_numpy()
    lat = df.loc[msk, "lat"].to_numpy()

    # Tile bounds
    xmin, xmax = df["lon"].min(), df["lon"].max()
    ymin, ymax = df["lat"].min(), df["lat"].max()

    # Create a binary mask in a small raster grid (bins x bins)
    # bin edges
    x_edges = np.linspace(xmin, xmax, bins + 1)
    y_edges = np.linspace(ymin, ymax, bins + 1)

    # Assign each labeled point to a bin
    xi = np.clip(np.searchsorted(x_edges, lon, side="right") - 1, 0, bins - 1)
    yi = np.clip(np.searchsorted(y_edges, lat, side="right") - 1, 0, bins - 1)

    mask = np.zeros((bins, bins), dtype=np.uint8)
    mask[yi, xi] = 1  # any labeled cell marks the bin

    # Make an RGBA image: red where mask=1, fully transparent elsewhere
    rgba = np.zeros((bins, bins, 4), dtype=np.uint8)
    rgba[..., 0] = (mask * 255)            # R
    rgba[..., 3] = (mask * 200)            # Alpha (200/255)
    # Flip vertically so image aligns with map (top-left origin vs lat ascending)
    rgba = np.flipud(rgba)

    # Save to temp PNG
    tmp_png = os.path.join(tempfile.gettempdir(), "tile_labeled_overlay.png")
    Image.fromarray(rgba, mode="RGBA").save(tmp_png)

    # Folium map centered on tile
    m = folium.Map(location=[(ymin+ymax)/2, (xmin+xmax)/2], zoom_start=12, control_scale=True)

    # Outline the tile
    folium.Rectangle(bounds=[(ymin, xmin), (ymax, xmax)], color="black", weight=1, fill=False).add_to(m)

    # Add raster overlay
    folium.raster_layers.ImageOverlay(
        name="Labeled pixels",
        image=tmp_png,
        bounds=[(ymin, xmin), (ymax, xmax)],
        opacity=1.0,
        interactive=False,
        cross_origin=False
    ).add_to(m)

    folium.LayerControl().add_to(m)
    display(m)

