def tile_index_from_path(p: str) -> int:
    name = os.path.basename(p).strip().lower()
    # try common patterns, in order
    pats = [
        r'^tile_(\d+)\.parquet$',                 # tile_0000.parquet
        r'^tile_(\d+)\..*parquet$',               # tile_0000.snappy.parquet
        r'^(?:emb_|lab_)?tile_(\d+)(?:_.*)?\.parquet$',  # emb_tile_0_...parquet
    ]
    for pat in pats:
        m = re.match(pat, name)
        if m:
            return int(m.group(1))
    raise ValueError(f"Could not parse tile index from filename: {name!r}")

