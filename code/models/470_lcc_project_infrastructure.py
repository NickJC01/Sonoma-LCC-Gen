def rasterize_labels(path, bins):
    df = read_minimal(path, ["lon", "lat", "label"])
    xmin, ymin, xmax, ymax = df.lon.min(), df.lat.min(), df.lon.max(), df.lat.max()
    valid = ~df["label"].isin(LABEL_IGNORE)
    if not valid.any():
        return None, (xmin, ymin, xmax, ymax)
    lon, lat, lab = df.loc[valid, ["lon","lat","label"]].to_numpy().T
    x_edges = np.linspace(xmin, xmax, bins+1)
    y_edges = np.linspace(ymin, ymax, bins+1)
    xi = np.clip(np.searchsorted(x_edges, lon, "right")-1, 0, bins-1)
    yi = np.clip(np.searchsorted(y_edges, lat, "right")-1, 0, bins-1)
    canvas = np.zeros((bins, bins), dtype=np.uint8)
    canvas[yi, xi] = lab
    return canvas, (xmin, ymin, xmax, ymax)

