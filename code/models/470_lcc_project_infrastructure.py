def read_minimal(path, cols):
    """Small helper: read specific columns to pandas (pyarrow backend)."""
    tbl = pq.read_table(path, columns=cols)
    return tbl.to_pandas()

def get_bounds(path):
    """Tile bounds [xmin, ymin, xmax, ymax] from lon/lat columns."""
    df = read_minimal(path, ["lon", "lat"])
    return float(df.lon.min()), float(df.lat.min()), float(df.lon.max()), float(df.lat.max())

def rasterize_tile_mask(path, bins, label_ok):
    """
    Return (mask[bins,bins], bounds) where mask=1 where labeled pixels occur.
    Uses lon/lat + label columns only.
    """
    df = read_minimal(path, ["lon", "lat", "label"])
    xmin, ymin, xmax, ymax = df.lon.min(), df.lat.min(), df.lon.max(), df.lat.max()
    msk_pts = ~df["label"].isin(label_ok)
    if not msk_pts.any():
        return np.zeros((bins, bins), dtype=np.uint8), (xmin, ymin, xmax, ymax)

    lon = df.loc[msk_pts, "lon"].to_numpy()
    lat = df.loc[msk_pts, "lat"].to_numpy()

    # bin edges
    x_edges = np.linspace(xmin, xmax, bins + 1)
    y_edges = np.linspace(ymin, ymax, bins + 1)

    xi = np.clip(np.searchsorted(x_edges, lon, side="right") - 1, 0, bins - 1)
    yi = np.clip(np.searchsorted(y_edges, lat, side="right") - 1, 0, bins - 1)

    mask = np.zeros((bins, bins), dtype=np.uint8)
    mask[yi, xi] = 1
    return mask, (xmin, ymin, xmax, ymax)

def save_rgba(mask, path_png):
    """
    Save binary mask (0/1) as red RGBA PNG (north-up).
    Input mask index [row=y, col=x] assumed south->north increasing; flip for display.
    """
    m = np.flipud(mask)  # folium expects top-left origin
    rgba = np.zeros((m.shape[0], m.shape[1], 4), dtype=np.uint8)
    rgba[..., 0] = m * 255       # red
    rgba[..., 3] = m * 200       # alpha
    Image.fromarray(rgba, mode="RGBA").save(path_png)

